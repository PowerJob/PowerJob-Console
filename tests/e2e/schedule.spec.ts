import { jobSection } from './job-ui'
import { test, expect, selectors, fill, check, clickAndResponse, cancelDialog, enterSamples, id, ownedName, processors, observation } from './helpers'
import { OwnedResources } from './owned'
import { cronCases, configureCron, validateCron } from './cron-oracle'

for (const rule of cronCases) {
  test(`UI-012 · fresh native Job CRON ${rule.key} builder, real Server calendar validation and hard-refresh persistence`, async ({ page, backend, credentials }, info) => {
    const ledger = new OwnedResources(backend)
    const name = ownedName(`cron_job_${rule.key}`)
    try {
      await enterSamples(page, credentials)
      await page.goto('/#/oms/job')
      await page.getByRole('button', { name: 'New job', exact: true }).click()
      const editor = selectors.dialog(page, 'New job')
      await fill(editor, 'Job name', name)
      await fill(editor, 'Processor', processors.simple)
      await check(editor, 'Enable job', false)
      await jobSection(editor, 'Schedule')
      await editor.getByLabel('Schedule type', { exact: true }).selectOption('CRON')
      const manual = '0 11 13 ? * MON#2 *'
      await fill(editor, 'Schedule expression', manual)
      const draft = await configureCron(page, editor, rule, false)
      expect(await editor.getByLabel('Schedule expression', { exact: true }).inputValue()).toBe(manual)
      await cancelDialog(page, 'CRON quick setup')
      await expect(editor.getByLabel('Schedule expression', { exact: true })).toHaveValue(manual)
      await expect(editor.getByRole('button', { name: 'Quick setup', exact: true })).toBeFocused()
      await configureCron(page, editor, rule)
      await expect(editor.getByLabel('Schedule expression', { exact: true })).toHaveValue(rule.expression)
      const dates = await validateCron(page, editor, backend, rule)
      // Opening a supported generated expression must restore that rule; complex expressions remain untouched until Apply.
      await editor.getByRole('button', { name: 'Quick setup', exact: true }).click()
      await expect(draft.getByLabel('Frequency', { exact: true })).toHaveValue(rule.frequency)
      for (const [label, value] of Object.entries(rule.fields)) await expect(draft.getByLabel(label, { exact: true })).toHaveValue(String(value))
      await draft.getByLabel('Frequency', { exact: true }).press('Escape')
      await expect(draft).not.toBeVisible()
      await expect(editor.getByRole('button', { name: 'Quick setup', exact: true })).toBeFocused()
      await expect(editor.getByLabel('Schedule expression', { exact: true })).toHaveValue(rule.expression)
      expect((await clickAndResponse(page, '/job/save', () => editor.getByRole('button', { name: 'Save job', exact: true }).click())).success).toBe(true)
      await expect(editor).not.toBeVisible()
      const saved = (await backend.listJobs(name)).data.find(job => job.jobName === name)!
      ledger.track('job', id(saved.id), name)
      expect(saved.timeExpressionType).toBe('CRON')
      expect(saved.timeExpression).toBe(rule.expression)
      expect(saved.enable).toBe(false)
      await page.reload()
      await fill(page, 'Keyword', name)
      expect((await clickAndResponse(page, '/job/list', () => page.getByRole('button', { name: 'Search', exact: true }).click(), response => response.request().postDataJSON()?.keyword === name)).success).toBe(true)
      await selectors.row(page, name).getByRole('button', { name: 'Edit', exact: true }).click()
      const reopened = selectors.dialog(page, 'Edit job')
      await jobSection(reopened, 'Schedule')
      await expect(reopened.getByLabel('Schedule expression', { exact: true })).toHaveValue(rule.expression)
      await cancelDialog(page, 'Edit job')
      await observation(info, 'UI-012', `fev3-cron-job-${rule.key}`, { jobId: id(saved.id), expression: rule.expression, realNativeCreateAndReadback: true, realServerCalendar: dates, hardRefreshAndReopen: true, recognizedDraftRestored: true, cancelAndEscapePreservedManualOrGeneratedValue: true, disabledDefinitionNoScheduledSideEffects: true })
    } finally { await ledger.cleanup(info) }
  })
}

