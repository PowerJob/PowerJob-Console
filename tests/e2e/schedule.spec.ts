test('UI-012 · all six native schedule modes, Daily first-fill/Tab and lifecycle clearing retain real DTO values', async ({ page, backend, credentials }, info) => {
  test.setTimeout(180_000)
  const ledger = new OwnedResources(backend)
  const name = ownedName('schedule_modes')
  try {
    await enterSamples(page, credentials)
    await page.goto('/#/oms/job')
    await page.getByRole('button', { name: 'New job', exact: true }).click()
    let editor = selectors.dialog(page, 'New job')
    await fill(editor, 'Job name', name)
    await fill(editor, 'Processor', processors.simple)
    await check(editor, 'Enable job', false)
    await jobSection(editor, 'Schedule')
    await fill(editor, 'Lifecycle start', '2032-01-01T01:02:03')
    await fill(editor, 'Lifecycle end', '2033-01-01T04:05:06')
    expect((await clickAndResponse(page, '/job/save', () => editor.getByRole('button', { name: 'Save job', exact: true }).click())).success).toBe(true)
    await expect(editor).not.toBeVisible()
    const job = (await backend.listJobs(name)).data.find(value => value.jobName === name)!
    ledger.track('job', id(job.id), name)
    const start = Date.parse('2032-01-01T01:02:03+08:00')
    const end = Date.parse('2033-01-01T04:05:06+08:00')
    expect(job.lifeCycle).toMatchObject({ start, end })
    for (const [type, expression] of [['API', ''], ['CRON', '0 0 9 * * ?'], ['FIXED_RATE', '10000'], ['FIXED_DELAY', '10000'], ['WORKFLOW', ''], ['DAILY_TIME_INTERVAL', '']] as const) {
      await fill(page, 'Keyword', name)
      expect((await clickAndResponse(page, '/job/list', () => page.getByRole('button', { name: 'Search', exact: true }).click(), response => response.request().postDataJSON()?.keyword === name)).success).toBe(true)
      await selectors.row(page, name).getByRole('button', { name: 'Edit', exact: true }).click()
      editor = selectors.dialog(page, 'Edit job')
      await jobSection(editor, 'Schedule')
      await editor.getByLabel('Schedule type', { exact: true }).selectOption(type)
      if (type === 'DAILY_TIME_INTERVAL') {
        // Clear the prior numeric expression before opening the structured daily editor.
        await fill(editor, 'Schedule expression', '')
        await editor.getByRole('button', { name: 'Set daily interval', exact: true }).click()
        const daily = selectors.dialog(page, 'Daily interval')
        await fill(daily, 'Interval', 7)
        await daily.getByLabel('Unit', { exact: true }).selectOption('MINUTES')
        await fill(daily, 'Daily start time', '09:05:07')
        await daily.getByLabel('Daily start time', { exact: true }).press('Tab')
        await fill(daily, 'Daily end time', '18:23:45')
        await daily.getByLabel('Daily end time', { exact: true }).press('Tab')
        for (const day of ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday']) await check(daily, day, day === 'Monday' || day === 'Wednesday')
        await daily.getByRole('button', { name: 'Apply configuration', exact: true }).click()
        await expect(daily).not.toBeVisible()
      } else if (expression) await fill(editor, 'Schedule expression', expression)
      expect((await clickAndResponse(page, '/job/save', () => editor.getByRole('button', { name: 'Save job', exact: true }).click())).success).toBe(true)
      await expect(editor).not.toBeVisible()
      const actual = (await backend.job(id(job.id)))!
      expect(actual.timeExpressionType).toBe(type)
      expect(actual.enable).toBe(false)
      expect(actual.lifeCycle).toMatchObject({ start, end })
      if (type === 'DAILY_TIME_INTERVAL') expect(JSON.parse(String(actual.timeExpression))).toMatchObject({ interval: 7, intervalUnit: 'MINUTES', startTimeOfDay: '09:05:07', endTimeOfDay: '18:23:45', daysOfWeek: [1, 3] })
      else if (expression) expect(actual.timeExpression).toBe(expression)
      await observation(info, 'UI-012', `timeExpressionType-${type.toLowerCase()}`, { jobId: id(job.id), nativeModeChangedAndSaved: true, actualType: actual.timeExpressionType, actualExpression: actual.timeExpression, actualLifecycle: actual.lifeCycle, disabledDefinition: true, actualSchedulingExecution: 'NOT_RUN_IN_THIS_ROUNDTRIP_TEST' })
    }
    await selectors.row(page, name).getByRole('button', { name: 'Edit', exact: true }).click()
    editor = selectors.dialog(page, 'Edit job')
    await jobSection(editor, 'Schedule')
    await fill(editor, 'Lifecycle start', '')
    await fill(editor, 'Lifecycle end', '')
    expect((await clickAndResponse(page, '/job/save', () => editor.getByRole('button', { name: 'Save job', exact: true }).click())).success).toBe(true)
    expect((await backend.job(id(job.id)))?.lifeCycle).toMatchObject({ start: null, end: null })
    await observation(info, 'UI-012', 'lifeCycle-valid', { realNativeEpochRoundtrip: { start, end }, browserTimezone: 'Asia/Shanghai' })
    await observation(info, 'UI-012', 'lifeCycle-unset', { realNativeClearingAndServerReadback: { start: null, end: null } })
  } finally { await ledger.cleanup(info) }
})

