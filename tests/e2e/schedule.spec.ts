test('UI-012 · real Server CRON invalid preview and invalid lifecycle retain native drafts without false save', async ({ page, backend, credentials }, info) => {
  const ledger = new OwnedResources(backend)
  const name = ownedName('schedule_invalid')
  try {
    await enterSamples(page, credentials)
    await page.goto('/#/oms/job')
    await page.getByRole('button', { name: 'New job', exact: true }).click()
    const editor = selectors.dialog(page, 'New job')
    await fill(editor, 'Job name', name)
    await fill(editor, 'Processor', processors.simple)
    await check(editor, 'Enable job', false)
    await jobSection(editor, 'Schedule')
    await editor.getByLabel('Schedule type', { exact: true }).selectOption('CRON')
    const valid = cronCases[0]
    await fill(editor, 'Schedule expression', valid.expression)
    const actualDates = await validateCron(page, editor, backend, valid)
    await observation(info, 'UI-012', 'cron-preview-valid', { realServerFutureDatesAndActualListMatched: actualDates })
    await fill(editor, 'Schedule expression', 'not a quartz cron')
    const invalid = await clickAndResponse<unknown>(page, '/validate/timeExpression', () => editor.getByRole('button', { name: 'Validate expression', exact: true }).click())
    expect(invalid.success).toBe(true)
    expect(Array.isArray(invalid.data)).toBe(true)
    const errorText = (invalid.data as string[]).join('\n')
    expect(errorText).not.toBe('')
    expect(errorText).not.toMatch(/^\d{4}-\d{2}-\d{2}/)
    const validation = selectors.dialog(page, 'Schedule validation')
    await expect(validation).toContainText(errorText)
    await expect(validation.getByRole('listitem')).toHaveCount(0)
    await validation.locator('footer').getByRole('button', { name: 'Close', exact: true }).click()
    await observation(info, 'UI-012', 'cron-preview-invalid', { originalServerSuccessEnvelopeWithErrorData: true, actualErrorDataVisible: errorText, zeroFakeFutureRows: true })
    await fill(editor, 'Schedule expression', valid.expression)
    await fill(editor, 'Lifecycle start', '2033-01-01T00:00')
    await fill(editor, 'Lifecycle end', '2032-01-01T00:00')
    let saves = 0
    page.on('request', request => { if (new URL(request.url()).pathname.endsWith('/job/save')) saves++ })
    await editor.getByRole('button', { name: 'Save job', exact: true }).click()
    await expect(editor.getByRole('alert')).toContainText('Lifecycle start must not be after end')
    expect(saves).toBe(0)
    await expect(editor.getByLabel('Lifecycle start', { exact: true })).toHaveValue('2033-01-01T00:00')
    expect((await backend.listJobs(name)).data.some(value => value.jobName === name)).toBe(false)
    await observation(info, 'UI-012', 'lifeCycle-invalid', { nativeInvertedEpochDraftRetained: true, zeroServerWrites: true, noActiveJobDefinitionCreated: true })
    await cancelDialog(page, 'New job')
  } finally { await ledger.cleanup(info) }
})
